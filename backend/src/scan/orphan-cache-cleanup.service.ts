import { Injectable, Logger, OnApplicationBootstrap } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { Cron, CronExpression, Interval } from '@nestjs/schedule';
import { promises as fs } from 'fs';
import { join } from 'path';
import { Photo } from '../photos/photo.entity';
import { QueuedSlide } from '../photos/queued-slide.entity';
import { CacheStorageService } from './cache-storage.service';

const EVICTION_INTERVAL_MS = 60 * 1000;
// Skip files younger than this so a cache file mid-write by an in-progress
// scan (written to disk fractionally before its Photo row is committed)
// never gets swept up as a false-positive orphan.
const MIN_FILE_AGE_MS = 60 * 1000;
// How long a cache file is kept around after it was last useful: either
// actually shown, or generated by prewarm but never consumed.
const CACHE_EVICTION_DELAY_MS = 5 * 60 * 1000;

const DEFAULT_DATA_DIR = join(__dirname, '..', '..', 'data');

@Injectable()
export class OrphanCacheCleanupService implements OnApplicationBootstrap {
  private readonly logger = new Logger(OrphanCacheCleanupService.name);
  private readonly cacheDir = join(process.env.FOTIFY_DATA_DIR ?? DEFAULT_DATA_DIR, 'cache');
  private running = false;

  constructor(
    @InjectRepository(Photo) private readonly photoRepo: Repository<Photo>,
    @InjectRepository(QueuedSlide) private readonly queuedSlideRepo: Repository<QueuedSlide>,
    private readonly cacheStorage: CacheStorageService,
  ) {}

  /**
   * True orphans (a cache file with no matching Photo row at all) should
   * only ever come from something going wrong — a crash mid-delete, a bug —
   * not from normal operation, so they're rare. Rather than wait up to a
   * full day for the first check, sweep once at startup too, in case any
   * built up while the app was down or before this existed.
   */
  async onApplicationBootstrap(): Promise<void> {
    await this.sweepOrphans().catch((err) => this.logger.error('Startup orphan sweep failed', err));
  }

  @Interval(EVICTION_INTERVAL_MS)
  handleEvictionInterval(): void {
    this.runExclusively(() => this.evictStaleCache()).catch((err) =>
      this.logger.error('Cache eviction sweep failed', err),
    );
  }

  /**
   * True orphans are a rare, abnormal-case cleanup (see above), so this
   * doesn't need per-minute checking like the eviction sweep — a daily pass
   * is enough to keep the disk from ever accumulating cache "for a long
   * time for some reason" without walking the whole cache directory
   * constantly.
   */
  @Cron(CronExpression.EVERY_DAY_AT_3AM)
  handleDailyOrphanSweep(): void {
    this.runExclusively(() => this.sweepOrphans()).catch((err) =>
      this.logger.error('Daily orphan sweep failed', err),
    );
  }

  private async runExclusively<T>(fn: () => Promise<T>): Promise<T | undefined> {
    if (this.running) return undefined;
    this.running = true;
    try {
      return await fn();
    } finally {
      this.running = false;
    }
  }

  /**
   * Reclaims cache files after they stop being useful. Shown photos age out
   * from lastShownAt; prewarmed-but-never-shown photos age out from cachedAt,
   * unless they are still in the persisted lookahead queue.
   */
  private async evictStaleCache(): Promise<number> {
    const cutoff = new Date(Date.now() - CACHE_EVICTION_DELAY_MS);
    const candidates = await this.photoRepo
      .createQueryBuilder('photo')
      .where('photo.cachedDisplayPath IS NOT NULL')
      .andWhere(
        '((photo.lastShownAt IS NOT NULL AND photo.lastShownAt < :cutoff) OR ' +
          '(photo.lastShownAt IS NULL AND photo.cachedAt IS NOT NULL AND photo.cachedAt < :cutoff))',
        { cutoff },
      )
      .getMany();

    const protectedIds = await this.queuedPhotoIds();

    let evicted = 0;
    for (const photo of candidates) {
      if (protectedIds.has(photo.id)) continue;
      const fresh = await this.photoRepo.findOneBy({ id: photo.id });
      if (!fresh || fresh.cachedDisplayPath !== photo.cachedDisplayPath) continue;
      if (
        fresh.mediaType === 'video' &&
        fresh.cachedAt &&
        Date.now() < fresh.cachedAt.getTime() + CACHE_EVICTION_DELAY_MS
      ) {
        continue;
      }
      if (
        fresh.mediaType === 'video' &&
        fresh.lastShownAt &&
        Date.now() <
          fresh.lastShownAt.getTime() +
            (fresh.durationMs ?? 0) +
            CACHE_EVICTION_DELAY_MS
      ) {
        continue;
      }
      const path = photo.cachedDisplayPath;
      if (!path) continue;

      await this.cacheStorage.delete(path);
      const result = await this.photoRepo.update(
        { id: fresh.id, cachedDisplayPath: path },
        { cachedDisplayPath: null, cachedAt: null, cachedVideoMode: null },
      );
      if (result.affected === 1) evicted += 1;
    }

    if (evicted > 0) {
      this.logger.log(`Evicted ${evicted} stale/unused cache file(s)`);
    }
    return evicted;
  }

  private async queuedPhotoIds(): Promise<Set<number>> {
    const ids = new Set<number>();
    const rows = await this.queuedSlideRepo.find({ select: ['photoIds'] });
    for (const row of rows) {
      for (const id of row.photoIds) ids.add(id);
    }
    return ids;
  }

  /** Deletes cache files on disk that no Photo row references any longer. */
  private async sweepOrphans(): Promise<{ scanned: number; deleted: number }> {
    let scanned = 0;
    let deleted = 0;

    const inUse = new Set(
      (await this.photoRepo.find({ select: ['cachedDisplayPath'] }))
        .map((p) => p.cachedDisplayPath)
        .filter((p): p is string => p !== null),
    );

    const shardEntries = await fs.readdir(this.cacheDir, { withFileTypes: true }).catch(() => []);
    for (const shard of shardEntries) {
      if (!shard.isDirectory()) continue;
      const shardPath = join(this.cacheDir, shard.name);
      const files = await fs.readdir(shardPath).catch(() => []);

      for (const file of files) {
        const filePath = join(shardPath, file);
        scanned += 1;
        if (inUse.has(filePath)) continue;

        const stat = await fs.stat(filePath).catch(() => null);
        if (!stat || Date.now() - stat.mtimeMs < MIN_FILE_AGE_MS) continue;

        await this.cacheStorage.delete(filePath);
        deleted += 1;
      }
    }

    if (deleted > 0) {
      this.logger.log(`Orphan cache sweep: removed ${deleted} unreferenced file(s) of ${scanned} scanned`);
    } else {
      this.logger.log(`Orphan cache sweep: no orphans found (${scanned} cache file(s) checked)`);
    }
    return { scanned, deleted };
  }
}
